import pptxgen from "pptxgenjs";

const COLORS = {
  dark: "0F172A",
  primary: "2563EB",
  white: "FFFFFF",
  offWhite: "F8FAFC",
  text: "1E293B",
  muted: "64748B",
  card: "EFF6FF",
};

export const generatePpt = async (data) => {
  const ppt = new pptxgen();

  ppt.layout = "LAYOUT_WIDE";
  ppt.author = "AestheAI";
  ppt.subject = data.subtitle || "";
  ppt.company = "AestheAI";
  ppt.lang = "en-US";

  ppt.theme = {
    headFontFace: "Aptos",
    bodyFontFace: "Aptos",
    lang: "en-US",
  };

  // Cover
  addCover(ppt, data);

  // Content slides
  data?.slides?.forEach((slideData, index) => {
    addContentSlide(
      ppt,
      slideData.title,
      slideData.points,
      index + 1,
      data.slides.length
    );
  });

  // Final slide
  addThankYou(ppt);

  return ppt;
};


// =========================
// COVER SLIDE
// =========================

const addCover = (ppt, data) => {
  const slide = ppt.addSlide();

  slide.background = {
    color: COLORS.primary,
  };

  // Top accent
  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 0,
    w: 13.33,
    h: 0.18,
    fill: {
      color: "60A5FA",
    },
    line: {
      color: "60A5FA",
    },
  });

  // Title
  slide.addText(data.title || "AestheAI Presentation", {
    x: 0.7,
    y: 2.0,
    w: 11.9,
    h: 0.8,
    fontSize: 28,
    bold: true,
    color: COLORS.white,
    fontFace: "Aptos",
    align: "center",
  });

  // Subtitle
  if (data.subtitle) {
    slide.addText(data.subtitle, {
      x: 1,
      y: 2.8,
      w: 11.3,
      h: 0.5,
      fontSize: 15,
      color: COLORS.white,
      fontFace: "Aptos",
      align: "center",
    });
  }

  // Footer
  slide.addText("Generated by AestheAI", {
    x: 0,
    y: 6.8,
    w: 13.33,
    h: 0.2,
    fontSize: 10,
    bold: true,
    color: "BFDBFE",
    fontFace: "Aptos",
    align: "center",
  });
};


// =========================
// CONTENT SLIDE
// =========================

const addContentSlide = (
  ppt,
  title,
  points,
  page,
  total
) => {
  const slide = ppt.addSlide();

  slide.background = {
    color: COLORS.white,
  };

  // Title
  slide.addText(title || "Untitled Slide", {
    x: 0.7,
    y: 0.35,
    w: 11.9,
    h: 0.6,
    fontSize: 26,
    bold: true,
    color: COLORS.primary,
    fontFace: "Aptos",
  });

  // Divider
  slide.addShape(ppt.ShapeType.line, {
    x: 0.6,
    y: 1.05,
    w: 12.1,
    h: 0,

    line: {
      color: COLORS.dark,
      width: 1.2,
    },
  });

  // Maximum 6 points
  const visiblePoints = points?.slice(0, 6) || [];

  visiblePoints.forEach((point, index) => {
    const y = 1.35 + index * 0.75;

    // Card
    slide.addShape(ppt.ShapeType.roundRect, {
      x: 0.6,
      y,
      w: 12.1,
      h: 0.58,

      fill: {
        color: index % 2
          ? COLORS.offWhite
          : COLORS.card,
      },

      line: {
        color: "E2E8F0",
        width: 0.5,
      },

      radius: 0.08,
    });

    // Bullet circle
    slide.addShape(ppt.ShapeType.ellipse, {
      x: 0.85,
      y: y + 0.2,
      w: 0.12,
      h: 0.12,

      fill: {
        color: COLORS.primary,
      },

      line: {
        color: COLORS.primary,
      },
    });

    // Point text
    slide.addText(point, {
      x: 1.1,
      y: y + 0.08,
      w: 11.1,
      h: 0.35,

      fontSize: 15,
      color: COLORS.text,
      fontFace: "Aptos",

      breakLine: false,
      margin: 0,
      valign: "mid",
      fit: "shrink",
    });
  });

  // Page number
  slide.addText(`${page}/${total}`, {
    x: 12.1,
    y: 6.9,
    w: 0.6,
    h: 0.2,

    align: "right",
    fontSize: 10,
    color: COLORS.muted,
  });

  // Footer
  slide.addText("AestheAI", {
    x: 0.6,
    y: 6.9,
    w: 1,
    h: 0.2,

    fontSize: 10,
    color: COLORS.muted,
  });
};


// =========================
// THANK YOU SLIDE
// =========================

const addThankYou = (ppt) => {
  const slide = ppt.addSlide();

  slide.background = {
    color: COLORS.dark,
  };

  slide.addText("Thank You", {
    x: 0,
    y: 2.2,
    w: 13.33,
    h: 0.8,

    align: "center",
    fontSize: 34,
    color: COLORS.white,
    bold: true,
    fontFace: "Aptos",
  });

  slide.addText("Generated by AestheAI", {
    x: 0,
    y: 3.15,
    w: 13.33,
    h: 0.4,

    align: "center",
    fontSize: 14,
    color: "94A3B8",
    fontFace: "Aptos",
  });
};