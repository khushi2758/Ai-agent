import PDFDocument from "pdfkit";

// Claude-inspired palette
const THEME = {
  bg: "#FAF9F5",
  text: "#141413",
  body: "#3D3D3A",
  muted: "#83827D",
  accent: "#D97757",
  rule: "#E8E6DC",
};

const FONT = {
  heading: "Times-Bold",
  body: "Helvetica",
  bodyBold: "Helvetica-Bold",
};

export const generatePdf = (data = {}) => {
  return new Promise((resolve, reject) => {
    try {
      const M = 60;

      const doc = new PDFDocument({
        size: "A4",
        margin: M,
        bufferPages: true,
        info: {
          Title: data.title || "AestheAI Document",
          Author: "AestheAI",
          Subject: data.subtitle || "",
          Creator: "AestheAI PDF Agent",
        },
      });

      const chunks = [];
      doc.on("data", (chunk) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      const pageW = doc.page.width;
      const pageH = doc.page.height;
      const contentW = pageW - M * 2;

      // Paint cream background + top accent bar on every page
      const paintPage = () => {
        doc.save();
        doc.rect(0, 0, pageW, pageH).fill(THEME.bg);
        doc.rect(0, 0, pageW, 6).fill(THEME.accent);
        doc.restore();
        doc.x = M;
        doc.y = M;
      };

      paintPage();
      doc.on("pageAdded", paintPage);

      // ---------- Brand mark ----------
      doc
        .font(FONT.bodyBold)
        .fontSize(9)
        .fillColor(THEME.accent)
        .text("AESTHEAI", M, doc.y, { characterSpacing: 2 });

      doc.moveDown(1.5);

      // ---------- Title ----------
      doc
        .font(FONT.heading)
        .fontSize(30)
        .fillColor(THEME.text)
        .text(data.title || "AestheAI Document", M, doc.y, {
          width: contentW,
          align: "left",
          lineGap: 2,
        });

      // ---------- Subtitle ----------
      if (data.subtitle) {
        doc.moveDown(0.4);
        doc
          .font(FONT.body)
          .fontSize(13)
          .fillColor(THEME.muted)
          .text(data.subtitle, M, doc.y, { width: contentW, lineGap: 3 });
      }

      // ---------- Header divider ----------
      doc.moveDown(1);
      doc
        .moveTo(M, doc.y)
        .lineTo(pageW - M, doc.y)
        .lineWidth(1)
        .strokeColor(THEME.rule)
        .stroke();

      doc.moveDown(1.5);

      // ---------- Sections ----------
      data?.sections?.forEach((section) => {
        // Avoid orphaned headings near the bottom of a page
        if (doc.y > pageH - 140) doc.addPage();

        const headingY = doc.y;
        doc.rect(M, headingY + 3, 4, 18).fill(THEME.accent);

        doc
          .font(FONT.heading)
          .fontSize(18)
          .fillColor(THEME.text)
          .text(section.heading || "", M + 14, headingY, {
            width: contentW - 14,
          });

        doc.moveDown(0.6);

        section?.points?.forEach((point) => {
          // Keep a bullet together with its text on one page
          if (doc.y > pageH - 100) doc.addPage();

          const startY = doc.y;

          doc.circle(M + 6, startY + 6, 2.5).fill(THEME.accent);

          doc
            .font(FONT.body)
            .fontSize(11.5)
            .fillColor(THEME.body)
            .text(point, M + 20, startY, {
              width: contentW - 20,
              lineGap: 4,
            });

          doc.moveDown(0.4);
        });

        doc.x = M;
        doc.moveDown(1.2);
      });

      // ---------- Footer + page numbers on every page ----------
      const range = doc.bufferedPageRange();

      for (let i = range.start; i < range.start + range.count; i++) {
        doc.switchToPage(i);

        // Stop PDFKit from adding a page while writing in the bottom margin
        const oldBottom = doc.page.margins.bottom;
        doc.page.margins.bottom = 0;

        const footerY = pageH - 40;

        doc
          .moveTo(M, footerY - 10)
          .lineTo(pageW - M, footerY - 10)
          .lineWidth(0.5)
          .strokeColor(THEME.rule)
          .stroke();

        doc
          .font(FONT.body)
          .fontSize(9)
          .fillColor(THEME.muted)
          .text("Generated by AestheAI", M, footerY, {
            width: contentW / 2,
            align: "left",
            lineBreak: false,
          });

        doc.text(`${i + 1} / ${range.count}`, M + contentW / 2, footerY, {
          width: contentW / 2,
          align: "right",
          lineBreak: false,
        });

        doc.page.margins.bottom = oldBottom;
      }

      doc.end();
    } catch (error) {
      reject(error);
    }
  });
};